package io.quarkus.oidc.test;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.util.List;
import java.util.logging.Level;
import java.util.logging.LogRecord;

import jakarta.ws.rs.GET;
import jakarta.ws.rs.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;

import io.quarkus.oidc.AuthenticationContext;
import io.quarkus.test.QuarkusExtensionTest;
import io.restassured.RestAssured;

/**
 * Tests that a warning is logged when the {@link AuthenticationContext} annotation is used,
 * but the 'web-app' tenant does not require an ID token, because Quarkus generates the internal ID token.
 */
public class AuthenticationContextIdTokenNotRequiredWarningTest {

    private static final String WARNING_START = "Step Up Authentication is not supported";

    @RegisterExtension
    static final QuarkusExtensionTest test = new QuarkusExtensionTest()
            .withApplicationRoot(jar -> jar.addClass(StepUpAuthResource.class))
            // starting the dev service would be a waste
            .overrideConfigKey("quarkus.devservices.enabled", "false")
            .overrideConfigKey("quarkus.http.auth.proactive", "false")
            // the OIDC provider is not contacted during the startup when the discovery is disabled
            .overrideRuntimeConfigKey("quarkus.oidc.auth-server-url", "http://localhost:8180/oidc")
            .overrideRuntimeConfigKey("quarkus.oidc.discovery-enabled", "false")
            .overrideRuntimeConfigKey("quarkus.oidc.authorization-path", "authorize")
            .overrideRuntimeConfigKey("quarkus.oidc.token-path", "token")
            .overrideRuntimeConfigKey("quarkus.oidc.user-info-path", "userinfo")
            .overrideRuntimeConfigKey("quarkus.oidc.client-id", "quarkus-app")
            .overrideRuntimeConfigKey("quarkus.oidc.credentials.secret", "secret")
            .overrideRuntimeConfigKey("quarkus.oidc.application-type", "web-app")
            .overrideRuntimeConfigKey("quarkus.oidc.authentication.id-token-required", "false")
            .setLogRecordPredicate(r -> r.getMessage() != null && r.getMessage().startsWith(WARNING_START))
            .assertLogRecords(AuthenticationContextIdTokenNotRequiredWarningTest::assertWarning);

    @Test
    public void testStepUpAuthenticationNotSupportedWarning() {
        // the warning is logged when the tenant is created during the application startup,
        // here we only make sure that the annotated endpoint requires authentication
        RestAssured.given().redirects().follow(false)
                .get("/step-up-auth")
                .then().statusCode(302);
    }

    private static void assertWarning(List<LogRecord> records) {
        assertEquals(1, records.size(), "The step-up authentication warning must be logged exactly once");
        LogRecord warning = records.get(0);
        assertEquals(Level.WARNING, warning.getLevel());
        assertEquals(WARNING_START + " for tenant 'Default', because the internal IdToken is generated by Quarkus."
                + " Please see the 'quarkus.oidc.authentication.id-token-required' configuration property documentation"
                + " for more information", String.format(warning.getMessage(), warning.getParameters()));
    }

    @Path("step-up-auth")
    public static class StepUpAuthResource {

        @AuthenticationContext("gold")
        @GET
        public String stepUpAuth() {
            return "step-up-auth";
        }

    }
}
